package com.shutdowntracker.projectworker.handoff;

import com.shutdowntracker.projectexport.contract.ProjectExportArtifactGenerationRequest;
import com.shutdowntracker.projectexport.contract.ProjectExportArtifactGenerationResponse;
import com.shutdowntracker.projectexport.contract.ProjectExportArtifactSummary;
import com.shutdowntracker.projectworker.exporter.ProjectExportArtifactService;
import com.shutdowntracker.projectworker.storage.WorkerStoragePathResolver;
import java.nio.file.Path;
import java.util.Objects;
import org.springframework.stereotype.Service;

@Service
public class WorkerProjectExportArtifactHandoffService {

    private static final String MESSAGE =
            "MSPDI/XML artifact generated by project worker. No Microsoft Project write-back was run.";

    private final ProjectExportArtifactService exportArtifactService;
    private final WorkerStoragePathResolver storagePathResolver;

    public WorkerProjectExportArtifactHandoffService(
            ProjectExportArtifactService exportArtifactService,
            WorkerStoragePathResolver storagePathResolver
    ) {
        this.exportArtifactService = exportArtifactService;
        this.storagePathResolver = storagePathResolver;
    }

    public ProjectExportArtifactGenerationResponse generateArtifact(ProjectExportArtifactGenerationRequest request) {
        Objects.requireNonNull(request, "request is required.");
        Path outputPath = storagePathResolver.resolveExportArtifactOutput(request.outputPath());
        ProjectExportArtifactSummary summary = exportArtifactService.generate(request.artifactRequest(), outputPath);

        return new ProjectExportArtifactGenerationResponse(
                request.exportBatchId(),
                request.projectId(),
                outputPath.toUri().toString(),
                summary.sha256(),
                summary,
                MESSAGE
        );
    }
}
